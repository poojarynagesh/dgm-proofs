"""Build assets/search-index.js for the DGM proofs site. Run: python tools/build_index.py"""
import html, json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
PAGES = [("home","index.html"),("p01","p01_foundations.html"),("p02","p02_fdiv_gan.html"),("p03","p03_lvm_elbo.html"),
 ("p04","p04_vae_ddpm_elbo.html"),("p05","p05_ddpm_loss.html"),("p06","p06_flow_matching.html"),("p07","p07_attention.html"),
 ("p08","p08_policy_gradient.html"),("p09","p09_rlhf_ssm.html")]
TOKEN = re.compile(r'<h([23])([^>]*)>(.*?)</h\1>', re.S)
def text(f): return re.sub(r"\s+"," ",html.unescape(re.sub(r"<[^>]+>","",f))).strip()
def slug(s): return re.sub(r"[^a-z0-9]+","-",s.lower()).strip("-")[:60]
def main():
    avail, ent = [], []
    for pid, rel in PAGES:
        path = ROOT/rel
        if not path.exists(): continue
        avail.append(pid); src = path.read_text(encoding="utf-8")
        m = re.search(r"<title>(.*?)</title>", src, re.S); where = text(m.group(1)).split(" — ")[0] if m else ""
        for m in TOKEN.finditer(src):
            label = text(m.group(3)); idm = re.search(r'id="([^"]+)"', m.group(2))
            ent.append({"t": label, "p": where, "u": f"{rel}#{idm.group(1) if idm else slug(label)}"})
    (ROOT/"assets"/"search-index.js").write_text(
        "// Generated by tools/build_index.py\n"
        f"window.RL_AVAILABLE = {json.dumps(avail)};\nwindow.DGM_SEARCH = {json.dumps(ent, ensure_ascii=False)};\n", encoding="utf-8")
    print(len(ent), "entries,", len(avail), "pages")
main()
